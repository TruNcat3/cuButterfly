#!/usr/bin/env python3
"""Export the frozen paper evidence manifest to deterministic paper artifacts.

This tool intentionally reads only experiments/provenance/manifest.json.  Source result
files are provenance inputs recorded by hash in that manifest; they are not
re-read during export, so a later evolving result matrix cannot change the
paper table accidentally.
"""

from __future__ import annotations

import argparse
import json
import math
from collections import Counter
from pathlib import Path
from typing import Any


DEFAULT_MANIFEST = Path(__file__).resolve().parents[1] / "provenance" / "manifest.json"
DEFAULT_OUTPUT_DIR = Path(__file__).resolve().parents[1] / "snapshots"


def _load_manifest(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as stream:
        manifest = json.load(stream)
    if manifest.get("schema") != "cubutterfly-paper-evidence-v1":
        raise ValueError(f"unexpected evidence schema in {path}")
    if manifest.get("frozen") is not True:
        raise ValueError("export requires a frozen manifest")
    rows = manifest.get("comparison_rows")
    if not isinstance(rows, list) or not rows:
        raise ValueError("frozen manifest has no comparison_rows")
    return manifest


def _latex_escape(value: object) -> str:
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def _ratio(row: dict[str, Any]) -> float:
    baseline = float(row["baseline_kernel_us"])
    cubutterfly = float(row["cubutterfly_kernel_us"])
    if baseline <= 0 or cubutterfly <= 0:
        raise ValueError(f"non-positive latency in {row['id']}")
    ratio = baseline / cubutterfly
    recorded = float(row["ratio_baseline_over_cubutterfly"])
    if not math.isclose(ratio, recorded, rel_tol=0.0, abs_tol=1.0e-6):
        raise ValueError(
            f"ratio mismatch in {row['id']}: computed {ratio:.12f}, recorded {recorded:.12f}"
        )
    if row.get("correct") is not True:
        raise ValueError(f"selected row is not correctness-qualified: {row['id']}")
    return ratio


def _workload(row: dict[str, Any]) -> str:
    precision = str(row["precision"])
    if row["operator"] == "ntt":
        operator = "NTT64/60" if "60" in precision else "NTT"
    else:
        operator = f"{str(row['operator']).upper()}{'64' if '64' in precision else '32'}"
    layout = "in" if row.get("placement") == "in-place" else "out"
    order = " nat" if row.get("output_order") == "natural" else ""
    direction = {"forward": "fwd", "inverse": "inv"}.get(
        row.get("direction"), str(row.get("direction", ""))[:3]
    )
    return f"{operator} $2^{{{row['logN']}}}\\times {row['batch']}$ {direction} {layout}{order}"


def _baseline_label(name: str) -> str:
    return {
        "Dao-AILab-FHT": "Dao",
        "Dao-FWHT": "Dao",
        "GPU-NTT-Merge-natural": "GPU-NTT",
    }.get(name, name)


def _quality_short(quality: str) -> str:
    if quality.startswith("unstable"):
        return "unstable"
    if "quick" in quality:
        return "stable,3t"
    if "3 trials" in quality:
        return "complete,3t"
    return "stable"


def _table(manifest: dict[str, Any]) -> str:
    cohorts = {cohort["id"]: cohort for cohort in manifest["cohorts"]}
    lines = [
        "% Generated by experiments/tools/export_evidence.py; do not edit by hand.",
        "% Input: experiments/provenance/manifest.json (frozen historical evidence).",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Selected transform timings from frozen experimental cohorts. Protocols and interface differences are identified below.}",
        r"\label{tab:frozen-results}",
        r"\small",
        r"\begin{tabular}{lllrrrl}",
        r"\hline",
        r"Cohort & Workload & Baseline & Ours ($\mu$s) & Base ($\mu$s) & Base/Cub & Quality \\",
        r"\hline",
    ]
    for row in manifest["comparison_rows"]:
        ratio = _ratio(row)
        cohort = cohorts[row["cohort"]]
        workload = _workload(row)
        lines.append(
            "{} & {} & {} & {:.3f} & {:.3f} & {:.3f} & {} \\\\".format(
                _latex_escape(cohort["table_id"]),
                workload,
                _latex_escape(_baseline_label(row["baseline"])),
                float(row["cubutterfly_kernel_us"]),
                float(row["baseline_kernel_us"]),
                ratio,
                _latex_escape(_quality_short(row["quality"])),
            )
        )
    lines.extend(
        [
            r"\hline",
            r"\end{tabular}",
            r"\parbox{0.98\linewidth}{\footnotesize Cohorts: V1=V100 focused vectorized FFT (5 trials), V2=V100 external (5 trials), A40q=A100 40GB quick FFT (3 trials), A40x=A100 40GB external (5 trials), A80=A100 80GB acceptance (3 trials, 5/72 cells). Shapes are $N\times B$; fwd/in and fwd/out indicate forward in-place and out-of-place execution. \texttt{NTT64/60} uses uint64 words and modulus $576460756061519873$; \texttt{nat} means natural output. Ratios are baseline time divided by cuButterfly time. Dao timings include the PyTorch interface and output allocation. The A40x FWHT row is unstable. Cohorts are not averaged.}",
            r"\end{table*}",
            "",
        ]
    )
    return "\n".join(lines)


def _summary(manifest: dict[str, Any]) -> dict[str, Any]:
    rows = manifest["comparison_rows"]
    cohorts = {cohort["id"]: cohort for cohort in manifest["cohorts"]}
    ratios = [_ratio(row) for row in rows]
    rows_by_cohort = Counter(row["cohort"] for row in rows)
    rows_by_operator = Counter(row["operator"] for row in rows)
    return {
        "schema": "cubutterfly-paper-evidence-export-v1",
        "frozen_on": manifest["frozen_on"],
        "generated_from": "experiments/provenance/manifest.json",
        "source_files_are_not_read": True,
        "row_count": len(rows),
        "correct_rows": sum(1 for row in rows if row.get("correct") is True),
        "rows_by_cohort": dict(sorted(rows_by_cohort.items())),
        "rows_by_operator": dict(sorted(rows_by_operator.items())),
        "ratio_min": min(ratios),
        "ratio_max": max(ratios),
        "cohort_completion": {
            cohort_id: cohort.get("completion", {"status": "historical selected rows"})
            for cohort_id, cohort in cohorts.items()
        },
        "claims": manifest["claims"],
        "gaps": manifest["gaps"],
        "factorial_ablation": manifest["factorial_ablation"],
        "composition_study": manifest["composition_study"],
        "source_sha256": {
            source["id"]: source["sha256"] for source in manifest["sources"]
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    args = parser.parse_args()

    manifest = _load_manifest(args.manifest)
    table = _table(manifest)
    summary = _summary(manifest)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "results_table.tex").write_text(table, encoding="ascii")
    (args.output_dir / "provenance_summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="ascii"
    )
    print(f"wrote {args.output_dir / 'results_table.tex'}")
    print(f"wrote {args.output_dir / 'provenance_summary.json'}")
    print(f"exported {len(manifest['comparison_rows'])} frozen comparison rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
