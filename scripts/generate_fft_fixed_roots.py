#!/usr/bin/env python3
"""Emit exact FP64-rounded power-of-two roots for constant local FFT phases.

The existing decimal80 generator constructs roots without a rounded pi.
Only template-indexed constants are exposed to device code; no runtime array
lookup, transcendental function or extra GPU allocation is introduced.
"""
from pathlib import Path
from compile_module import local_root_values

ROOT = Path(__file__).resolve().parents[1]


def render():
    values = local_root_values(12, "fp64")
    lines = ["// Generated by scripts/generate_fft_fixed_roots.py; decimal80, FP64 RNE.",
        "#pragma once", "#include <type_traits>", "#include <utility>",
        "namespace cuntt::detail::register_tile {",
        "namespace fixed_coefficients {", "struct Pair { double real, imag; };",
        "inline constexpr Pair roots[4096] = {"]
    lines += ["    {"+x.hex()+", "+y.hex()+"}," for x,y in values]
    lines += ["};", "}",
        "template<unsigned Log, unsigned Exponent, bool Inverse, class Complex>",
        "__device__ __forceinline__ Complex fixed_root() {",
        '    static_assert(Log <= 12, "fixed local FFT roots support log sizes through 12");',
        "    using Real = decltype(Complex{}.real);",
        "    constexpr auto value = fixed_coefficients::roots[(Exponent & ((1U<<Log)-1)) << (12-Log)];",
        "    constexpr Real real = static_cast<Real>(value.real);",
        "    constexpr Real imag = static_cast<Real>(Inverse ? -value.imag : value.imag);",
        "    return {real, imag};", "}",
        "template<class F, unsigned... I>",
        "__device__ __forceinline__ void static_for_impl(F f, std::integer_sequence<unsigned,I...>) {",
        "    (f(std::integral_constant<unsigned,I>{}), ...);", "}",
        "template<unsigned N, class F>",
        "__device__ __forceinline__ void static_for(F f) {",
        "    static_for_impl(f, std::make_integer_sequence<unsigned,N>{});", "}", "}"]
    return "\n".join(lines)+"\n"


if __name__ == "__main__":
    (ROOT / "src/fft_fixed_roots.cuh").write_text(render())
